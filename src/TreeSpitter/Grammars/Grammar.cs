namespace TreeSpitter.Grammars;

/// <summary>A named rule of a grammar.</summary>
public sealed record GrammarRule(string Name, Rule Rule);

/// <summary>A named set of reserved words, see the <c>reserved</c> property of tree-sitter grammars.</summary>
public sealed record ReservedWordSet(string Name, IReadOnlyList<Rule> Rules);

/// <summary>
/// A tree-sitter grammar, as produced by evaluating a <c>grammar.js</c> file or by reading a <c>grammar.json</c> file.
/// </summary>
public sealed class Grammar
{
    private Dictionary<string, Rule>? _ruleMap;

    /// <summary>The name of the language.</summary>
    public required string Name { get; init; }

    /// <summary>The name of the grammar this one extends, if any.</summary>
    public string? Inherits { get; init; }

    /// <summary>The name of the rule used for keyword extraction, see <c>word</c>.</summary>
    public string? Word { get; init; }

    /// <summary>The rules, in declaration order. The first one is the start rule.</summary>
    public required IReadOnlyList<GrammarRule> Rules { get; init; }

    /// <summary>The tokens that can appear anywhere, usually white space and comments.</summary>
    public IReadOnlyList<Rule> Extras { get; init; } = [];

    /// <summary>The rule names that are intended to conflict (only meaningful for an LR parser).</summary>
    public IReadOnlyList<IReadOnlyList<string>> Conflicts { get; init; } = [];

    /// <summary>The ordered precedence lists. Entries are <see cref="StringRule"/> (names) or <see cref="SymbolRule"/>.</summary>
    public IReadOnlyList<IReadOnlyList<Rule>> Precedences { get; init; } = [];

    /// <summary>The tokens produced by an external scanner.</summary>
    public IReadOnlyList<Rule> Externals { get; init; } = [];

    /// <summary>The rules that are inlined where they are used. They never produce nodes.</summary>
    public IReadOnlyList<string> Inline { get; init; } = [];

    /// <summary>The hidden rules that are considered supertypes.</summary>
    public IReadOnlyList<string> Supertypes { get; init; } = [];

    /// <summary>The reserved word sets. The first one is the global set.</summary>
    public IReadOnlyList<ReservedWordSet> Reserved { get; init; } = [];

    /// <summary>The name of the start rule.</summary>
    public string StartRule => Rules.Count > 0 ? Rules[0].Name : throw new InvalidOperationException("The grammar has no rules.");

    /// <summary>Returns the rule with the specified name, or <c>null</c>.</summary>
    public Rule? GetRule(string name)
    {
        _ruleMap ??= BuildRuleMap();
        return _ruleMap.TryGetValue(name, out var rule) ? rule : null;
    }

    /// <summary>Serializes the grammar with the format of the <c>src/grammar.json</c> files generated by tree-sitter.</summary>
    public string ToJson(bool indented = true) => GrammarJsonWriter.Write(this, indented);

    private Dictionary<string, Rule> BuildRuleMap()
    {
        var map = new Dictionary<string, Rule>(StringComparer.Ordinal);
        foreach (var rule in Rules)
        {
            map[rule.Name] = rule.Rule;
        }

        return map;
    }
}
