using System.Runtime.CompilerServices;

namespace TreeSpitter;

/// <summary>The kind of a parse action.</summary>
internal enum ParseActionType : byte
{
    Shift = 0,
    Reduce = 1,
    Accept = 2,
    Recover = 3,
}

/// <summary>
/// A parse action or the header of an action list, packed in 64 bits like tree-sitter's <c>TSParseActionEntry</c>.
/// </summary>
/// <remarks>
/// Header: bits 0-15 the count, bit 16 reusable. Action: bits 0-1 the type, bit 2 extra, bit 3 repetition, bits 16-31 the
/// state (shift) or the symbol (reduce), bits 32-39 the child count, bits 40-55 the production id, bits 56-63 the dynamic
/// precedence (signed).
/// </remarks>
internal readonly struct ParseActionEntry(ulong value)
{
    public readonly ulong Value = value;

    public int Count
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => (int)(Value & 0xFFFF);
    }

    public bool Reusable
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => (Value & 0x10000) != 0;
    }

    public ParseActionType Type
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => (ParseActionType)(Value & 3);
    }

    public bool IsExtra
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => (Value & 4) != 0;
    }

    public bool IsRepetition
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => (Value & 8) != 0;
    }

    /// <summary>The state of a shift, the symbol of a reduce.</summary>
    public ushort StateOrSymbol
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => (ushort)(Value >> 16);
    }

    public int ChildCount
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => (int)((Value >> 32) & 0xFF);
    }

    public ushort ProductionId
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => (ushort)(Value >> 40);
    }

    public int DynamicPrecedence
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => (sbyte)(Value >> 56);
    }

    public static ulong Header(int count, bool reusable) => (ulong)(uint)count | (reusable ? 0x10000UL : 0UL);

    public static ulong Shift(int state, bool extra, bool repetition) =>
        (ulong)ParseActionType.Shift | (extra ? 4UL : 0) | (repetition ? 8UL : 0) | ((ulong)(ushort)state << 16);

    public static ulong Reduce(int symbol, int childCount, int dynamicPrecedence, int productionId) =>
        (ulong)ParseActionType.Reduce | ((ulong)(ushort)symbol << 16) | ((ulong)(byte)childCount << 32) | ((ulong)(ushort)productionId << 40) | ((ulong)unchecked((byte)dynamicPrecedence) << 56);

    public static ulong Accept() => (ulong)ParseActionType.Accept;

    public static ulong Recover() => (ulong)ParseActionType.Recover;
}

/// <summary>A field of a production: the field id and the index of the child among the non-extra children.</summary>
internal readonly record struct FieldMapEntry(ushort FieldId, byte ChildIndex, bool Inherited);

/// <summary>
/// A compiled tree-sitter grammar: the parse table, the lexer automata and the metadata of the symbols, fields and
/// aliases. This is the "bytecode" run by <see cref="Parser"/>, the equivalent of the <c>TSLanguage</c> generated by
/// <c>tree-sitter generate</c> in <c>parser.c</c>.
/// </summary>
public sealed partial class Language
{
    /// <summary>The symbol of the end of the input.</summary>
    public const ushort EndSymbol = 0;

    /// <summary>The symbol of <c>ERROR</c> nodes.</summary>
    public const ushort ErrorSymbol = ushort.MaxValue;

    /// <summary>The symbol of the hidden nodes which repeat errors.</summary>
    public const ushort ErrorRepeatSymbol = ushort.MaxValue - 1;

    /// <summary>The parse state of the error recovery.</summary>
    internal const ushort ErrorState = 0;

    /// <summary>The lex state of the parse states which end a non-terminal extra: no lookahead is lexed.</summary>
    internal const ushort NoLookaheadLexState = ushort.MaxValue;

    internal const byte VisibleFlag = 1;
    internal const byte NamedFlag = 2;
    internal const byte SupertypeFlag = 4;

    internal Language()
    {
    }

    /// <summary>Gets the name of the language.</summary>
    public string Name { get; internal set; } = "";

    /// <summary>Gets the number of symbols, aliases excluded.</summary>
    public int SymbolCount { get; internal set; }

    /// <summary>Gets the number of aliases which don't have the name of a symbol.</summary>
    public int AliasCount { get; internal set; }

    /// <summary>Gets the number of terminal symbols, including the end of the input.</summary>
    public int TokenCount { get; internal set; }

    /// <summary>Gets the number of external tokens.</summary>
    public int ExternalTokenCount { get; internal set; }

    /// <summary>Gets the number of parse states.</summary>
    public int StateCount { get; internal set; }

    /// <summary>Gets the number of field names.</summary>
    public int FieldCount { get; internal set; }

    /// <summary>Gets the number of production ids (distinct alias and field sequences).</summary>
    public int ProductionIdCount { get; internal set; }

    /// <summary>Gets the number of states of the lexer.</summary>
    public int LexStateCount => MainLexTable.StateCount;

    /// <summary>Gets the number of states of the keyword lexer.</summary>
    public int KeywordLexStateCount => KeywordLexTable.StateCount;

    /// <summary>Gets the number of entries of the parse action lists.</summary>
    public int ParseActionCount => ParseActions.Length;

    internal int MaxAliasSequenceLength { get; set; }

    internal string[] SymbolNames { get; set; } = [];

    internal byte[] SymbolFlags { get; set; } = [];

    internal ushort[] PublicSymbolMap { get; set; } = [];

    internal string?[] FieldNames { get; set; } = [null];

    /// <summary>[state * SymbolCount + symbol]: the index of the action list of a terminal, the goto state of a non-terminal.</summary>
    internal ushort[] ParseTable { get; set; } = [];

    internal ParseActionEntry[] ParseActions { get; set; } = [];

    internal ushort[] LexStates { get; set; } = [];

    internal ushort[] ExternalLexStates { get; set; } = [];

    internal ushort[] ReservedWordSetIds { get; set; } = [];

    /// <summary>[productionId * MaxAliasSequenceLength + childIndex]: the alias symbol, or 0.</summary>
    internal ushort[] AliasSequences { get; set; } = [];

    /// <summary>[productionId * 2]: the index of the first field map entry, [productionId * 2 + 1] the count.</summary>
    internal ushort[] FieldMapSlices { get; set; } = [];

    internal FieldMapEntry[] FieldMapEntries { get; set; } = [];

    internal ushort KeywordCaptureToken { get; set; }

    internal int MaxReservedWordSetSize { get; set; }

    /// <summary>[setId * MaxReservedWordSetSize + i]: the reserved words, 0-terminated.</summary>
    internal ushort[] ReservedWords { get; set; } = [];

    internal ushort[] SupertypeSymbols { get; set; } = [];

    private KeywordTable? _keywords;
    private bool _keywordsCreated;

    /// <summary>Disables the keyword table, to measure it.</summary>
    internal static bool DisableKeywordTable { get; set; }

    /// <summary>The keywords as a hash table, when the keyword automaton accepts a finite set of strings.</summary>
    internal KeywordTable? Keywords
    {
        get
        {
            if (!Volatile.Read(ref _keywordsCreated))
            {
                _keywords = DisableKeywordTable ? null : KeywordTable.Create(KeywordLexTable);
                Volatile.Write(ref _keywordsCreated, true);
            }

            return _keywords;
        }
    }

    /// <summary>The lexer of the tokens.</summary>
    internal LexAutomaton MainLexTable { get; set; } = LexAutomaton.Empty;

    /// <summary>The lexer of the keywords, which runs on the text of the word token.</summary>
    internal LexAutomaton KeywordLexTable { get; set; } = LexAutomaton.Empty;

    /// <summary>The names of the external tokens, in the order of the grammar's <c>externals</c>.</summary>
    internal string[] ExternalTokenNames { get; set; } = [];

    /// <summary>[externalToken]: the symbol of each external token.</summary>
    internal ushort[] ExternalScannerSymbolMap { get; set; } = [];

    /// <summary>[externalLexState * ExternalTokenCount + externalToken]: whether an external token is valid.</summary>
    internal bool[] ExternalScannerStates { get; set; } = [];

    /// <summary>Gets the name of a symbol.</summary>
    public string SymbolName(ushort symbol) => symbol switch
    {
        ErrorSymbol => "ERROR",
        ErrorRepeatSymbol => "_ERROR",
        _ => symbol < SymbolNames.Length ? SymbolNames[symbol] : throw new ArgumentOutOfRangeException(nameof(symbol)),
    };

    /// <summary>Gets whether a symbol is visible in the trees.</summary>
    public bool IsVisible(ushort symbol) => (Metadata(symbol) & VisibleFlag) != 0;

    /// <summary>Gets whether a symbol is named (a rule, as opposed to a string literal).</summary>
    public bool IsNamed(ushort symbol) => (Metadata(symbol) & NamedFlag) != 0;

    /// <summary>Gets the name of a field, by its id (1 to <see cref="FieldCount"/>).</summary>
    public string? FieldName(int fieldId) => fieldId > 0 && fieldId < FieldNames.Length ? FieldNames[fieldId] : null;

    /// <summary>Gets the id of a field, 0 if the language has no such field.</summary>
    public int FieldId(string name)
    {
        for (var i = 1; i < FieldNames.Length; i++)
        {
            if (FieldNames[i] == name)
            {
                return i;
            }
        }

        return 0;
    }

    /// <summary>Gets the symbol of a named or anonymous node type, or <c>null</c>.</summary>
    public ushort? SymbolForName(string name, bool isNamed)
    {
        if (name == "ERROR" && isNamed)
        {
            return ErrorSymbol;
        }

        for (var i = 0; i < SymbolNames.Length; i++)
        {
            if (SymbolNames[i] == name && IsVisible((ushort)i) && IsNamed((ushort)i) == isNamed)
            {
                return PublicSymbolMap[i];
            }
        }

        return null;
    }

    /// <summary>The public symbol of a symbol: symbols with the same name and kind share one public symbol.</summary>
    public ushort PublicSymbol(ushort symbol) => symbol >= ErrorRepeatSymbol ? symbol : PublicSymbolMap[symbol];

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    internal byte Metadata(ushort symbol) => symbol switch
    {
        ErrorSymbol => VisibleFlag | NamedFlag,
        ErrorRepeatSymbol => 0,
        _ => SymbolFlags[symbol],
    };

    /// <summary>The index of the action list for a terminal in a state, tree-sitter's <c>ts_language_lookup</c>.</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    internal int Lookup(int state, int symbol) => ParseTable[state * SymbolCount + symbol];

    /// <summary>The actions of a terminal in a state: the index of the first action and the count.</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    internal int TableEntry(int state, ushort symbol, out int count, out bool reusable)
    {
        if (symbol >= ErrorRepeatSymbol)
        {
            count = 0;
            reusable = false;
            return 0;
        }

        var index = ParseTable[state * SymbolCount + symbol];
        var header = ParseActions[index];
        count = header.Count;
        reusable = header.Reusable;
        return index + 1;
    }

    internal bool HasActions(int state, ushort symbol)
    {
        TableEntry(state, symbol, out var count, out _);
        return count > 0;
    }

    internal bool HasReduceAction(int state, ushort symbol)
    {
        var index = TableEntry(state, symbol, out var count, out _);
        return count > 0 && ParseActions[index].Type == ParseActionType.Reduce;
    }

    /// <summary>The state after a symbol, tree-sitter's <c>ts_language_next_state</c>.</summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    internal ushort NextState(int state, ushort symbol)
    {
        if (symbol >= ErrorRepeatSymbol)
        {
            return 0;
        }

        if (symbol < TokenCount)
        {
            var index = ParseTable[state * SymbolCount + symbol];
            var count = ParseActions[index].Count;
            if (count > 0)
            {
                var action = ParseActions[index + count];
                if (action.Type == ParseActionType.Shift)
                {
                    return action.IsExtra ? (ushort)state : action.StateOrSymbol;
                }
            }

            return 0;
        }

        return ParseTable[state * SymbolCount + symbol];
    }

    internal bool IsReservedWord(int state, ushort symbol)
    {
        var setId = ReservedWordSetIds[state];
        if (setId > 0)
        {
            var start = setId * MaxReservedWordSetSize;
            var end = start + MaxReservedWordSetSize;
            for (var i = start; i < end; i++)
            {
                if (ReservedWords[i] == symbol)
                {
                    return true;
                }

                if (ReservedWords[i] == 0)
                {
                    break;
                }
            }
        }

        return false;
    }

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    internal ushort AliasAt(int productionId, int childIndex) =>
        productionId > 0 && childIndex < MaxAliasSequenceLength ? AliasSequences[productionId * MaxAliasSequenceLength + childIndex] : (ushort)0;

    internal ReadOnlySpan<FieldMapEntry> FieldMap(int productionId)
    {
        if (productionId * 2 + 1 >= FieldMapSlices.Length)
        {
            return default;
        }

        var start = FieldMapSlices[productionId * 2];
        var length = FieldMapSlices[productionId * 2 + 1];
        return new ReadOnlySpan<FieldMapEntry>(FieldMapEntries, start, length);
    }
}
