using System.Globalization;
using System.Text;

namespace TreeSpitter.CodeGen;

/// <summary>The options of <see cref="CSharpGenerator"/>.</summary>
public sealed class CSharpGeneratorOptions
{
    /// <summary>The namespace of the generated class, none when null or empty.</summary>
    public string? Namespace { get; set; }

    /// <summary>The name of the generated class.</summary>
    public string ClassName { get; set; } = "GeneratedLanguage";

    /// <summary>The accessibility of the generated class (<c>public</c> or <c>internal</c>), or null for a partial class
    /// whose accessibility is declared elsewhere.</summary>
    public string? Accessibility { get; set; } = "public";

    /// <summary>Whether the class is static.</summary>
    public bool IsStatic { get; set; } = true;

    /// <summary>The fully qualified name of the external scanner class of the language, if any.</summary>
    public string? ExternalScanner { get; set; }
}

/// <summary>
/// Generates the C# source of a precompiled parser: the tables of a <see cref="Language"/> are embedded in their binary
/// format, and the keywords are matched by code (switches on their length and on chunks of their bytes). The generated
/// class exposes the language and creates parsers.
/// </summary>
public static class CSharpGenerator
{
    /// <summary>Generates the source of a class for a language.</summary>
    public static string Generate(Language language, CSharpGeneratorOptions? options = null)
    {
        if (language is null)
        {
            throw new ArgumentNullException(nameof(language));
        }

        options ??= new CSharpGeneratorOptions();
        var builder = new StringBuilder();
        var writer = new CodeWriter(builder);
        writer.Line("// <auto-generated/>");
        writer.Line($"// The parser of the '{language.Name}' language, generated by TreeSpitter: {language.StateCount} parse states, {language.SymbolCount} symbols, {language.LexStateCount} lex states.");
        writer.Line("#nullable enable");
        writer.Line("#pragma warning disable");
        writer.Line();

        var hasNamespace = !string.IsNullOrEmpty(options.Namespace);
        if (hasNamespace)
        {
            writer.Line($"namespace {options.Namespace}");
            writer.Open();
        }

        var modifiers = (options.Accessibility is null ? "" : options.Accessibility + " ") + (options.IsStatic ? "static " : "");
        writer.Line($"/// <summary>The parser of the <c>{Escape(language.Name)}</c> language, generated by TreeSpitter.</summary>");
        writer.Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"TreeSpitter\", \"{typeof(CSharpGenerator).Assembly.GetName().Version}\")]");
        writer.Line($"{modifiers}partial class {options.ClassName}");
        writer.Open();

        writer.Line("/// <summary>Gets the language, loaded once from the embedded tables.</summary>");
        writer.Line("public static global::TreeSpitter.Language Language => Holder.Instance;");
        writer.Line();
        writer.Line("/// <summary>Creates a parser for the language.</summary>");
        writer.Line("public static global::TreeSpitter.Parser CreateParser() => new global::TreeSpitter.Parser(Language);");
        writer.Line();
        writer.Line("private static class Holder");
        writer.Open();
        WriteData(writer, language.Save());
        writer.Line();
        writer.Line("public static readonly global::TreeSpitter.Language Instance = Create();");
        writer.Line();
        writer.Line("private static global::TreeSpitter.Language Create()");
        writer.Open();
        writer.Line("var language = global::TreeSpitter.Language.Load(Data);");
        writer.Line(options.ExternalScanner is { } scanner
            ? $"return language.WithLexFunction(new LexFunction(language.TableLexFunction)).WithExternalScanner(static () => new {scanner}());"
            : "return language.WithLexFunction(new LexFunction(language.TableLexFunction));");
        writer.Close();
        writer.Close();
        writer.Line();

        // The lexer automata are run by the table lexer: compiled to C#, they weren't faster when the JIT optimized them,
        // and the large ones were 20 to 30% slower, compiled without optimizations. The keywords are matched by code.
        writer.Line("private readonly struct LexFunction : global::TreeSpitter.ILexFunction");
        writer.Open();
        writer.Line("private readonly global::TreeSpitter.TableLexFunction _tables;");
        writer.Line();
        writer.Line("public LexFunction(global::TreeSpitter.TableLexFunction tables)");
        writer.Open();
        writer.Line("_tables = tables;");
        writer.Close();
        writer.Line();
        writer.Line("public bool Lex(global::TreeSpitter.Lexer lexer, int state) => _tables.Lex(lexer, state);");
        writer.Line();
        writer.Line("public bool LexKeyword(global::TreeSpitter.Lexer lexer, int state) => _tables.LexKeyword(lexer, state);");
        writer.Line();
        var keywords = language.Keywords;
        writer.Line(keywords is not null
            ? "public int MatchKeyword(global::System.ReadOnlySpan<byte> input, int start, int end) => MatchKeywords(input.Slice(start, end - start));"
            : "public int MatchKeyword(global::System.ReadOnlySpan<byte> input, int start, int end) => _tables.MatchKeyword(input, start, end);");
        writer.Close();

        if (keywords is not null)
        {
            // The keywords are recognized with switches on their length and on chunks of their bytes read as integers
            writer.Line();
            writer.Line("private static int MatchKeywords(global::System.ReadOnlySpan<byte> input)");
            writer.Open();
            var body = KnownBytesLookup.Generate(
                keywords.Entries.Select(e => e.Key).ToList(),
                index => keywords.Entries[index].Value.ToString(CultureInfo.InvariantCulture),
                "-1");
            foreach (var line in body.Split('\n'))
            {
                if (line.Length > 0)
                {
                    writer.Line(line);
                }
            }

            writer.Close();
        }

        writer.Close();
        if (hasNamespace)
        {
            writer.Close();
        }

        return builder.ToString();
    }

    /// <summary>
    /// Writes the serialized tables as a span of a constant array, which the compiler stores in the data of the assembly:
    /// <c>Language.Load</c> reads them there, without allocating or keeping a copy.
    /// </summary>
    private static void WriteData(CodeWriter writer, byte[] data)
    {
        writer.Line("private static global::System.ReadOnlySpan<byte> Data => new byte[]");
        writer.Line("{");
        var line = new StringBuilder();
        for (var i = 0; i < data.Length; i++)
        {
            line.Append(data[i].ToString(CultureInfo.InvariantCulture)).Append(',');
            if (line.Length > 110 || i == data.Length - 1)
            {
                writer.Line("    " + line);
                line.Clear();
            }
        }

        writer.Line("};");
    }

    internal static string Escape(string value) => value.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    internal sealed class CodeWriter(StringBuilder builder)
    {
        private int _indent;

        public void Line(string text = "")
        {
            if (text.Length > 0)
            {
                builder.Append(' ', _indent * 4);
            }

            builder.Append(text).Append('\n');
        }

        public void Open()
        {
            Line("{");
            _indent++;
        }

        public void Close(string suffix = "")
        {
            _indent--;
            Line("}" + suffix);
        }
    }
}
